"""ESM-2 embedding extraction and logistic-regression evaluation."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

import numpy as np
import pandas as pd
import torch
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (average_precision_score, balanced_accuracy_score,
                             classification_report, confusion_matrix,
                             f1_score, precision_score, recall_score,
                             roc_auc_score)
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

from strokeprot.model1.splitting import split_indices

CHECKPOINT = "esm2_t6_8M_UR50D"
LAYER = 6
MAX_RESIDUES = 1022
STANDARD_AA = set("ACDEFGHIKLMNPQRSTVWY")
REQUIRED = {"protein_accession", "sequence", "label"}


def read_proteins(path: str | Path) -> pd.DataFrame:
    data = pd.read_csv(path, dtype={"protein_accession": "string", "sequence": "string"})
    missing = REQUIRED - set(data.columns)
    if missing:
        raise ValueError(f"Missing required columns: {sorted(missing)}")
    if data.empty or data[list(REQUIRED)].isna().any().any():
        raise ValueError("Input must contain non-empty rows and no missing required values.")
    data["protein_accession"] = data["protein_accession"].astype(str).str.strip()
    data["sequence"] = data["sequence"].astype(str).str.upper().str.replace(r"\s+", "", regex=True)
    if data["protein_accession"].duplicated().any() or data["sequence"].duplicated().any():
        raise ValueError("Resolve duplicate accessions and identical sequences before modeling.")
    invalid = data["sequence"].map(lambda s: set(s) - STANDARD_AA)
    if invalid.map(bool).any():
        raise ValueError("Sequences must use the 20 standard amino-acid symbols only.")
    labels = pd.to_numeric(data["label"], errors="coerce")
    if labels.isna().any() or not set(labels.unique()).issubset({0, 1}) or labels.nunique() != 2:
        raise ValueError("Both binary labels 0 and 1 are required; no labels are generated by this code.")
    data["label"] = labels.astype("int8")
    if "organism" in data and not data["organism"].astype(str).str.contains("Homo sapiens", case=False).all():
        raise ValueError("All sequences must be human.")
    if "cluster_id" in data and (data["cluster_id"].isna().any() or (data["cluster_id"].astype(str).str.strip() == "").any()):
        raise ValueError("Fill cluster_id for every protein before using cluster-based evaluation.")
    return data.reset_index(drop=True)


def _sequence_embedding(sequence: str, model, alphabet, batch_converter, device: torch.device) -> np.ndarray:
    # ESM-2 has a finite token window. Window long proteins with overlap so no
    # residues are silently dropped; combine chunk means weighted by residues.
    stride = MAX_RESIDUES - 128
    chunks = [sequence[start:start + MAX_RESIDUES] for start in range(0, len(sequence), stride)]
    weighted = []
    with torch.no_grad():
        for chunk in chunks:
            _, _, tokens = batch_converter([("protein", chunk)])
            tokens = tokens.to(device)
            result = model(tokens, repr_layers=[LAYER], return_contacts=False)
            reps = result["representations"][LAYER][0, 1:len(chunk) + 1]
            weighted.append(reps.mean(dim=0).cpu().numpy() * len(chunk))
    return np.sum(weighted, axis=0) / sum(map(len, chunks))


def embed_dataset(data: pd.DataFrame, cache_path: str | Path, device_name: str = "auto") -> np.ndarray:
    cache_path = Path(cache_path)
    cache_path.parent.mkdir(parents=True, exist_ok=True)
    digest = hashlib.sha256("\n".join(data["sequence"]).encode()).hexdigest()
    if cache_path.exists():
        cached = np.load(cache_path, allow_pickle=False)
        if str(cached["sequence_sha256"].item()) == digest and cached["embeddings"].shape[0] == len(data):
            return cached["embeddings"]
    import esm

    device = torch.device("cuda" if device_name == "auto" and torch.cuda.is_available() else
                          "cpu" if device_name == "auto" else device_name)
    model, alphabet = esm.pretrained.esm2_t6_8M_UR50D()
    model.eval().to(device)
    vectors = np.vstack([_sequence_embedding(s, model, alphabet, alphabet.get_batch_converter(), device)
                         for s in data["sequence"]])
    np.savez_compressed(cache_path, embeddings=vectors, sequence_sha256=digest,
                        checkpoint=CHECKPOINT, layer=LAYER, pooling="mean residues; overlapping chunks")
    return vectors


def fit_evaluate(data: pd.DataFrame, vectors: np.ndarray, output_dir: str | Path,
                 random_pilot: bool = False, seed: int = 42) -> dict:
    output = Path(output_dir)
    output.mkdir(parents=True, exist_ok=True)
    partitions, split_type = split_indices(data, random_pilot=random_pilot, seed=seed)
    train, validation, test = (partitions[k] for k in ("train", "validation", "test"))
    # Threshold selected on validation F1; test set is evaluated once.
    head = make_pipeline(StandardScaler(), LogisticRegression(class_weight="balanced", max_iter=3000,
                                                                random_state=seed))
    head.fit(vectors[train], data.iloc[train]["label"])
    val_prob = head.predict_proba(vectors[validation])[:, 1]
    thresholds = np.linspace(0.05, 0.95, 181)
    val_scores = [f1_score(data.iloc[validation]["label"], val_prob >= t, zero_division=0) for t in thresholds]
    threshold = float(thresholds[int(np.argmax(val_scores))])
    test_labels = data.iloc[test]["label"].to_numpy()
    test_prob = head.predict_proba(vectors[test])[:, 1]
    test_pred = (test_prob >= threshold).astype(int)
    metrics = {
        "model": "ESM-2 frozen embeddings + Logistic Regression", "checkpoint": CHECKPOINT,
        "layer": LAYER, "pooling": "mean residue representation; overlapping chunks for sequences >1022 aa",
        "split_type": split_type, "seed": seed, "validation_selected_threshold": threshold,
        "n_train": int(len(train)), "n_validation": int(len(validation)), "n_test": int(len(test)),
        "precision": float(precision_score(test_labels, test_pred, zero_division=0)),
        "recall": float(recall_score(test_labels, test_pred, zero_division=0)),
        "f1": float(f1_score(test_labels, test_pred, zero_division=0)),
        "balanced_accuracy": float(balanced_accuracy_score(test_labels, test_pred)),
        "confusion_matrix_labels_0_1": confusion_matrix(test_labels, test_pred, labels=[0, 1]).tolist(),
        "roc_auc": float(roc_auc_score(test_labels, test_prob)),
        "pr_auc_average_precision": float(average_precision_score(test_labels, test_prob)),
        "test_classification_report": classification_report(test_labels, test_pred, output_dict=True, zero_division=0),
    }
    (output / "metrics.json").write_text(json.dumps(metrics, indent=2), encoding="utf-8")
    pd.DataFrame({"row_index": test, "protein_accession": data.iloc[test]["protein_accession"].to_numpy(),
                  "label": test_labels, "probability_label_1": test_prob, "prediction": test_pred}).to_csv(
                      output / "test_predictions.csv", index=False)
    import joblib
    joblib.dump(head, output / "logistic_regression.joblib")
    return metrics
